export function applyAuthorityResearchedExplanationBackfills(questions) {
  const backfillsById = new Map();
  for (const backfill of AUTHORITY_RESEARCHED_EXPLANATION_BACKFILLS) {
    if (backfillsById.has(backfill.id)) throw new Error(`权威检索解析题目重复：${backfill.id}`);
    if (!backfill.after.endsWith('（由AI查询）')) throw new Error(`权威检索解析缺少标记：${backfill.id}`);
    backfillsById.set(backfill.id, backfill);
  }

  const foundIds = new Set();
  const result = questions.map((question) => {
    const backfill = backfillsById.get(question.id);
    if (!backfill) return question;
    foundIds.add(question.id);
    if (question.explanation !== backfill.before) {
      throw new Error(`权威检索解析前值不匹配：${backfill.id}`);
    }
    return { ...question, explanation: backfill.after };
  });

  const missingIds = [...backfillsById.keys()].filter(id => !foundIds.has(id));
  if (missingIds.length) throw new Error(`权威检索解析题目不存在：${missingIds.join(', ')}`);
  return result;
}
