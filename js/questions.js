function makeQuestion(id, subject, chapter, knowledge, difficulty, stem, options, answer, explanation, type = 'A1', extra = {}) {
  const optionMap = Object.fromEntries(LETTERS.map((letter, index) => [letter, options[index]]));
  const optionExplanations = Object.fromEntries(LETTERS.map(letter => [
    letter,
    letter === answer
      ? `${optionMap[letter]}符合本题所考的“${knowledge}”。${explanation}`
      : `${optionMap[letter]}不是本题所问的最佳答案，应与“${knowledge}”的核心定义和适用范围区分。`
  ]));
  return {
    id, subject, chapter, knowledge, type, difficulty, stem,
    options: optionMap,
    answer,
    keyPoint: knowledge,
    explanation,
    correctExplanation: optionExplanations[answer],
    optionExplanations,
    commonMistake: `易把相近概念或相似功效混同；作答时应先锁定“${knowledge}”这一限定。`,
    mnemonic: `抓住关键词“${knowledge}”，再排除作用层次或适用证候不同的选项。`,
    relatedKnowledge: [chapter, knowledge],
    sourceType: '自主命题',
    sourceNote: '自主命题，依据中医类别医师资格考试大纲相关考点。',
    outlineVersion: OUTLINE,
    verificationStatus: 'V1 教学测试题，正式使用前建议由执业中医师复核',
    groupId: extra.groupId ?? null,
    caseId: extra.caseId ?? null,
    sharedStem: extra.sharedStem ?? null,
    optionSetId: extra.optionSetId ?? null
  };
}

